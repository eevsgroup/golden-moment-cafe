
/**
 * Checkout API calls for Golden Moment Café.
 *
 * When the backend is disabled, checkout operations return a clear
 * "not available" message instead of attempting network requests.
 */

import { APP_CONFIG } from "@/lib/config";
import { api } from "./client";
import type {
    CheckoutSessionRequest,
    CheckoutSessionResponse,
    Order,
} from "@golden-moment/contracts";

/**
 * Whether online checkout is currently available.
 * Components can use this to show/hide checkout UI.
 */
export function isCheckoutAvailable(): boolean {
    return APP_CONFIG.backendEnabled;
}

/**
 * Creates a Stripe Checkout session.
 *
 * idempotencyKey must be a UUID generated by the caller and reused
 * when retrying the same checkout attempt.
 */
export async function createCheckoutSession(
    payload: CheckoutSessionRequest,
    idempotencyKey: string
): Promise<{ url: string | null; error: string | null }> {
    if (!APP_CONFIG.backendEnabled) {
        return {
            url: null,
            error: "Online ordering is coming soon. Please call or visit us to place your order.",
        };
    }

    if (!idempotencyKey.trim()) {
        return {
            url: null,
            error: "Missing checkout request key. Please try again.",
        };
    }

    try {
        const result = await api.post<CheckoutSessionResponse>(
            "/api/checkout/create-session",
            payload,
            {
                headers: {
                    "Idempotency-Key": idempotencyKey,
                },
                // Retrying is safe only when the same key is reused.
                retries: 1,
                timeout: 12_000,
            }
        );

        if (result.data?.url) {
            return {
                url: result.data.url,
                error: null,
            };
        }

        return {
            url: null,
            error: result.error ?? "Failed to create checkout session.",
        };
    } catch {
        return {
            url: null,
            error: "Unable to connect to checkout. Please try again.",
        };
    }
}

/**
 * Fetches an order using its Stripe Checkout Session ID.
 */
export async function fetchOrder(
    sessionId: string
): Promise<{ order: Order | null; error: string | null }> {
    if (!APP_CONFIG.backendEnabled) {
        return {
            order: null,
            error: "Order lookup is not available in offline mode.",
        };
    }

    if (!sessionId.trim()) {
        return {
            order: null,
            error: "A checkout session ID is required.",
        };
    }

    try {
        const result = await api.get<Order>(
            `/api/checkout/order/${encodeURIComponent(sessionId)}`,
            {
                retries: 1,
                timeout: 8_000,
            }
        );

        if (result.data) {
            return {
                order: result.data,
                error: null,
            };
        }

        return {
            order: null,
            error: result.error ?? "Order not found.",
        };
    } catch {
        return {
            order: null,
            error: "Unable to retrieve your order. Please try again.",
        };
    }
}
